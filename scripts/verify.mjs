const ALL_LEVELS = (globalThis.KENARI_LEVELS || []).slice().sort((a, b) => a.n - b.n);
const LEVELS = levelArg === null ? ALL_LEVELS : ALL_LEVELS.filter((L) => L.n === levelArg);

const ALLOWED_DEMOS = new Set(['anatomy', 'order', 'join', 'join-left', 'group', 'fanout', 'window', 'transaction', 'index']);
const BANNED_FUNCS = /\b(pow|median|stdev|variance|mode|lower_quartile|upper_quartile|regexp)\s*\(/i;
const SOFT_WORDS = /\b(simply|just|obviously|easy|easily|basically|trivial|of course|clearly|stupid|dumb)\b/i;

const glossary = Object.assign({}, Ref.GLOSSARY);
ALL_LEVELS.forEach((L) => Object.assign(glossary, L.terms || {}));
const glossaryLower = new Set(Object.keys(glossary).map((k) => k.toLowerCase()));

const VOCAB = { values: Data.VALUES, columns: [...new Set(Data.SCHEMA.flatMap((t) => t.c.map((c) => c[0])))], tables: Data.SCHEMA.map((t) => t.t) };

const ref = freshDb();
ref.exec('PRAGMA query_only = 1');

let errors = 0, warnings = 0, missions = 0, todo = 0;
const fixtures = {};
const summary = [];

function say(kind, id, msg) {
  if (kind === 'ERROR') errors++; else warnings++;
  console.log(`${kind.padEnd(5)} ${id}: ${msg}`);
}

const plainText = (html) => String(html || '').replace(/\[\[demo:[^\]]+\]\]/g, ' ').replace(/\[\[([^\]|]+)(\|[^\]]+)?\]\]/g, '$1').replace(/<[^>]+>/g, ' ');
const wordCount = (html) => plainText(html).trim().split(/\s+/).filter(Boolean).length;

function checkTerms(id, html) {
  const re = /\[\[([^\]]+)\]\]/g;
  let m;
  while ((m = re.exec(String(html || '')))) {
    const inner = m[1];
    if (inner.startsWith('demo:')) {
      if (!ALLOWED_DEMOS.has(inner.slice(5))) say('ERROR', id, `unknown demo "${inner}". Allowed: ${[...ALLOWED_DEMOS].join(', ')}`);
      continue;
    }
    const key = inner.includes('|') ? inner.split('|')[1] : inner;
    if (!glossaryLower.has(key.trim().toLowerCase())) say('ERROR', id, `glossary term "${key}" is not defined. Add it to this level's terms field.`);
  }
}

function runExpected(lesson) {
  if (lesson.mode === 'state') {
    const d = freshDb();
    exec(d, lesson.solution);
    if (lesson.stateCheck) return null;
    return exec(d, lesson.stateQuery);
  }
  return exec(ref, lesson.solution);
}

function runAttempt(lesson, sql) {
  if (lesson.mode === 'state') {
    const d = freshDb();
    exec(d, sql);
    if (lesson.stateCheck) {
      const plan = exec(d, lesson.stateCheck.sql);
      const text = plan.rows.map((r) => r.join(' ')).join('\n');
      const ok = new RegExp(lesson.stateCheck.mustMatch, 'i').test(text);
      return { plan: text, ok };
    }
    return exec(d, lesson.stateQuery);
  }
  const d = freshDb();
  return exec(d, sql);
}

function attemptState(lesson, expected, sql) {
  if (lesson.mode === 'state' && lesson.stateCheck) {
    const r = runAttempt(lesson, sql);
    if (!r.ok) return { state: 'fail', title: 'plan check', body: r.plan };
    const clean = Check.stripComments(sql);
    for (const q of lesson.requires || []) if (!q.re.test(clean)) return { state: 'near', title: 'requires', body: q.msg };
    return { state: 'pass' };
  }
  return Check.compare(lesson, expected, runAttempt(lesson, sql), sql, VOCAB);
}

function verifyLesson(L, lesson) {
  const id = lesson.id;
  const type = lesson.type || 'write';
  missions++;

  /* Shape */
  if (!/^\d+\.\d+$/.test(id || '')) say('ERROR', id, 'id must look like 3.12');
  if (String(id).split('.')[0] !== String(L.n)) say('ERROR', id, `id does not belong to level ${L.n}`);
  if (!['write', 'fix', 'quiz', 'order'].includes(type)) say('ERROR', id, `unknown type ${type}`);
  for (const f of ['title', 'newIdea', 'teach', 'bridge', 'win']) if (!lesson[f]) say('ERROR', id, `missing ${f}`);
  if (type !== 'quiz' && !lesson.from) say('ERROR', id, 'missing from');
  if (type !== 'quiz' && !lesson.task) say('ERROR', id, 'missing task');
  if (lesson.title && lesson.title.length > 44) say('WARN', id, `title is long (${lesson.title.length} characters)`);

  /* Voice */
  const prose = [lesson.teach, lesson.task, lesson.question, lesson.bridge, lesson.win, lesson.exNote, lesson.atWork, ...(lesson.hints || [])].filter(Boolean);
  for (const p of prose) {
    if (/—/.test(p)) say('ERROR', id, `em dash in: "${plainText(p).slice(0, 60)}"`);
    const hit = plainText(p).match(SOFT_WORDS);
    if (hit) say('WARN', id, `word "${hit[0]}" in: "${plainText(p).slice(0, 60)}"`);
    checkTerms(id, p);
  }
  if (wordCount(lesson.teach) > 110) say('WARN', id, `teach is ${wordCount(lesson.teach)} words, aim for 110 or fewer`);
  if (wordCount(lesson.task || lesson.question) > 60) say('WARN', id, `task is ${wordCount(lesson.task || lesson.question)} words, aim for 60 or fewer`);
  if (JSON.stringify(lesson, (k, v) => (v instanceof RegExp ? v.source : v)).includes('TODO' + '(human)')) todo++;

  /* Annotated example */
  if (lesson.ex) {
    if (!Array.isArray(lesson.ex) || !lesson.ex.every((x) => Array.isArray(x) && x.length === 2 && x[0] && x[1])) {
      say('ERROR', id, 'ex must be an array of [sql line, plain English] pairs');
    } else {
      lesson.ex.forEach((x) => checkTerms(id, x[1]));
      const sql = lesson.ex.map((x) => x[0]).join('\n');
      if (BANNED_FUNCS.test(sql)) say('ERROR', id, 'example uses a function not available in both engines');
      try {
        const r = lesson.exState ? (() => { const d = freshDb(); return exec(d, sql); })() : exec(ref, sql);
        if (!lesson.exNoResult && (!r || !r.rows.length) && !lesson.exAllowEmpty) say('ERROR', id, 'example returned no rows');
        if (r && r.rows.length > 30 && !/LIMIT/i.test(sql) && !lesson.exNoResult) say('WARN', id, `example returns ${r.rows.length} rows, consider LIMIT`);
        fixtures[`${id}#ex`] = r ? digest(r) : null;
      } catch (e) { say('ERROR', id, `example fails: ${e.message}`); }
    }
  }

  /* Quiz */
  if (type === 'quiz') {
    if (!lesson.question) say('ERROR', id, 'quiz needs question');
    const ch = lesson.choices || [];
    if (ch.length < 2 || ch.length > 5) say('ERROR', id, 'quiz needs 2 to 5 choices');
    if (ch.filter((c) => c.correct).length !== 1) say('ERROR', id, 'quiz needs exactly one correct choice');
    ch.forEach((c, i) => {
      if (!c.t) say('ERROR', id, `choice ${i} has no text t`);
      if (!c.why) say('ERROR', id, `choice ${i} has no why`);
    });
    if (lesson.code) {
      try { exec(ref, lesson.code); } catch (e) { say('ERROR', id, `quiz code fails: ${e.message}`); }
    }
    if (lesson.check) {
      try {
        const r = exec(ref, lesson.check.sql);
        const val = r && r.rows[0] ? String(r.rows[0][0]) : '';
        if (val !== String(lesson.check.equals)) say('ERROR', id, `quiz check expected ${lesson.check.equals}, data says ${val}`);
      } catch (e) { say('ERROR', id, `quiz check fails: ${e.message}`); }
    }
    return;
  }

  /* Order */
  if (type === 'order') {
    if (!Array.isArray(lesson.lines) || lesson.lines.length < 2) say('ERROR', id, 'order needs lines');
    lesson.solution = lesson.solution || (lesson.lines || []).join('\n');
  }

  /* Write and fix */
  if (!lesson.solution) { say('ERROR', id, 'missing solution'); return; }
  const allSql = [lesson.solution, lesson.starter, ...(lesson.altSolutions || []), ...(lesson.wrong || [])].filter(Boolean).join('\n');
  if (BANNED_FUNCS.test(allSql)) say('ERROR', id, 'SQL uses a function not available in both engines (pow, median, stdev, and similar)');

  let expected = null;
  try {
    expected = runExpected(lesson);
    if (!(lesson.mode === 'state' && lesson.stateCheck)) {
      if (!expected) { say('ERROR', id, 'solution returned no table'); return; }
      if (!expected.rows.length && !lesson.allowEmpty) say('ERROR', id, 'solution returned 0 rows, so a blank result would pass');
      if (expected.rows.length > 500) say('WARN', id, `solution returns ${expected.rows.length} rows`);
      fixtures[id] = digest(expected);
      if (lesson.ordered && !expected.columns.includes(lesson.ordered)) say('ERROR', id, `ordered column ${lesson.ordered} is not in the result`);
    }
  } catch (e) { say('ERROR', id, `solution fails: ${e.message}`); return; }

  const expectPass = (label, sql) => {
    try {
      const v = attemptState(lesson, expected, sql);
      if (v.state !== 'pass') say('ERROR', id, `${label} did not pass: ${v.title}. ${plainText(v.body)}`);
    } catch (e) { say('ERROR', id, `${label} fails to run: ${e.message}`); }
  };
  expectPass('solution', lesson.solution);
  (lesson.altSolutions || []).forEach((s, i) => expectPass(`altSolutions[${i}]`, s));
  (lesson.wrong || []).forEach((s, i) => {
    try {
      const v = attemptState(lesson, expected, s);
      if (v.state === 'pass') say('ERROR', id, `wrong[${i}] passed, and it should not: ${s}`);
    } catch (e) { /* an error also counts as not passing */ }
  });

  /* Starter */
  if (lesson.starter !== undefined) {
    if (Check.hasBlanks(lesson.starter)) {
      if (!lesson.fill) say('ERROR', id, 'starter has blanks but no fill');
      else {
        const count = (Check.stripComments(lesson.starter).match(/_{3,}/g) || []).length;
        if (count !== lesson.fill.length) say('ERROR', id, `starter has ${count} blanks, fill has ${lesson.fill.length}`);
        expectPass('starter with fill', Check.fillBlanks(lesson.starter, lesson.fill));
      }
    } else if (type === 'fix' && !lesson.starterErrors) {
      try {
        const v = attemptState(lesson, expected, lesson.starter);
        if (v.state === 'pass') say('ERROR', id, 'fix mission: the buggy starter already passes');
      } catch (e) { say('ERROR', id, `fix mission: starter fails to run, set starterErrors: true if that is the point. ${e.message}`); }
    } else if (type === 'fix' && lesson.starterErrors) {
      let threw = false;
      try { runAttempt(lesson, lesson.starter); } catch (e) { threw = true; }
      if (!threw) say('ERROR', id, 'starterErrors is true but the starter ran without an error');
    }
  } else if (type === 'fix') say('ERROR', id, 'fix mission needs a starter');

  /* Hints, pattern, traps */
  const hints = lesson.hints || [];
  if (lesson.exam) { if (hints.length) say('ERROR', id, 'exam missions have no hints'); }
  else if (hints.length < 2 || hints.length > 4) say('ERROR', id, `needs 2 to 4 hints, has ${hints.length}`);
  if (!lesson.pattern && !lesson.exam && type !== 'order') say('ERROR', id, 'missing pattern');
  if (lesson.pattern && (!lesson.pattern.sql || !lesson.pattern.note)) say('ERROR', id, 'pattern needs sql and note');
  (lesson.traps || []).forEach((t, i) => { if (!(t.re instanceof RegExp) || !t.msg) say('ERROR', id, `traps[${i}] needs re (RegExp) and msg`); });
  (lesson.requires || []).forEach((t, i) => { if (!(t.re instanceof RegExp) || !t.msg) say('ERROR', id, `requires[${i}] needs re (RegExp) and msg`); });
}

/** Order-independent fingerprint of a result, used to compare Node's engine with the browser's. */
function digest(r) {
  /* EXPLAIN QUERY PLAN's id and notused columns are internal numbers that differ between SQLite versions. Compare the plan text. */
  const source = r.columns.join() === 'id,parent,notused,detail' ? r.rows.map((row) => [row[3]]) : r.rows;
  const rows = source.map((row) => row.map((v) => (typeof v === 'number' ? String(Math.round(v * 100) / 100) : String(v))).join('\u0001')).sort();
  let h = 0;
  for (const s of rows) for (let i = 0; i < s.length; i++) h = (Math.imul(h, 31) + s.charCodeAt(i)) | 0;
  return { n: r.rows.length, c: r.columns.length, h };
}

for (const L of LEVELS) {
  const before = { e: errors, w: warnings, m: missions };
  for (const f of ['n', 'title', 'rank', 'tagline', 'goal']) if (L[f] === undefined) say('ERROR', `level ${L.n}`, `missing ${f}`);
  const seen = new Set();
  for (const lesson of L.lessons || []) {
    if (seen.has(lesson.id)) say('ERROR', lesson.id, 'duplicate id');
    seen.add(lesson.id);
    try { verifyLesson(L, lesson); } catch (e) { say('ERROR', lesson.id, `crash: ${e.stack}`); }
  }
  summary.push(`Level ${L.n} (${L.title}): ${missions - before.m} missions, ${errors - before.e} errors, ${warnings - before.w} warnings`);
}

if (todo) say('ERROR', 'all', `Lessons must not hold a leftover author to-do mark, found ${todo}`);

if (flag('--fixtures')) {
  const dir = path.join(ROOT, 'tests');
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'fixtures.json'), JSON.stringify(fixtures));
  console.log(`Wrote tests/fixtures.json with ${Object.keys(fixtures).length} results`);
}

console.log('\n' + summary.join('\n'));
console.log(`\nTOTAL: ${missions} missions, ${errors} errors, ${warnings} warnings`);
process.exit(errors ? 1 : 0);
