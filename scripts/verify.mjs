function freshDb() {
  const d = new DatabaseSync(':memory:');
  Data.build(Data.nodeAdapter(d));
  return d;
}

function exec(d, sql) {
  let last = null;
  for (const stmt of Check.splitStatements(sql)) {
    const st = d.prepare(stmt);
    const cols = st.columns();
    if (cols.length) {
      st.setReturnArrays(true);
      last = { columns: cols.map((c) => c.name), rows: st.all() };
    } else {
      st.run();
    }
  }
  return last;
}

